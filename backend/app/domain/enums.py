class EventSource(str, Enum):
    MANUAL = "MANUAL"  # explicit API call
    AUTO_MATCH = "AUTO_MATCH"  # deterministic auto-assignment after a release
    SYSTEM = "SYSTEM"
    SEED = "SEED"


