from enum import Enum


class PatientStatus(str, Enum):
    REGISTERED = "REGISTERED"
    ADMITTED = "ADMITTED"
    TRANSFERRED = "TRANSFERRED"
    DISCHARGED = "DISCHARGED"


class BedStatus(str, Enum):
    AVAILABLE = "AVAILABLE"
    OCCUPIED = "OCCUPIED"
    CLEANING = "CLEANING"
    MAINTENANCE = "MAINTENANCE"


class BedType(str, Enum):
    GENERAL = "GENERAL"
    ICU = "ICU"
    EMERGENCY = "EMERGENCY"
    PEDIATRIC = "PEDIATRIC"
    SURGICAL = "SURGICAL"


class TheatreStatus(str, Enum):
    AVAILABLE = "AVAILABLE"
    IN_USE = "IN_USE"
    CLEANING = "CLEANING"
    UNAVAILABLE = "UNAVAILABLE"


class TheatreSlotStatus(str, Enum):
    AVAILABLE = "AVAILABLE"
    BOOKED = "BOOKED"
    COMPLETED = "COMPLETED"
    CANCELLED = "CANCELLED"


class SurgeryStatus(str, Enum):
    WAITING = "WAITING"
    SCHEDULED = "SCHEDULED"
    IN_PROGRESS = "IN_PROGRESS"
    COMPLETED = "COMPLETED"
    CANCELLED = "CANCELLED"


class StaffRole(str, Enum):
    SURGEON = "SURGEON"
    ANAESTHETIST = "ANAESTHETIST"
    DOCTOR = "DOCTOR"
    NURSE = "NURSE"
    PORTER = "PORTER"


class StaffStatus(str, Enum):
    AVAILABLE = "AVAILABLE"  # on shift and free to be assigned
    ASSIGNED = "ASSIGNED"  # has exactly one ACTIVE assignment
    OFF_DUTY = "OFF_DUTY"  # not working


class StaffAssignmentType(str, Enum):
    SURGERY = "SURGERY"
    PATIENT = "PATIENT"


class StaffAssignmentStatus(str, Enum):
    ACTIVE = "ACTIVE"
    RELEASED = "RELEASED"


class WaitlistResourceType(str, Enum):
    BED = "BED"
    THEATRE = "THEATRE"
    STAFF = "STAFF"


class WaitlistStatus(str, Enum):
    WAITING = "WAITING"
    FULFILLED = "FULFILLED"
    CANCELLED = "CANCELLED"


class ResourceType(str, Enum):
    """Resource kinds referenced by audit events and realtime messages."""

    PATIENT = "PATIENT"
    BED = "BED"
    DEPARTMENT = "DEPARTMENT"
    THEATRE = "THEATRE"
    THEATRE_SLOT = "THEATRE_SLOT"
